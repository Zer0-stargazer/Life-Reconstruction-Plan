/**
 * 内容过滤（输入 / 输出护栏）—— 基础兜底，非万能。
 *
 * ⚠ 定位：这是"高精度关键词过滤"，只做最后一道兜底。它挡不住精心变形的绕过
 *   （谐音 / 拼音 / 拆字 / 编码），也不能替代模型侧的官方内容审核。真正的合规
 *   依赖：系统提示词约束 + 选用带审核的国内模型 + 人工巡查。
 *
 * ⚠ 关键约束：**平台自身数据含大量"政治 / 赌博 / 性 / 颠覆"等词**——
 *   「职场政治」「技术颠覆」「酒精赌博」「婚前必须谈性」等都是正常内容。
 *   因此本词表**只收高精度、几乎不可能是正常用途的表述**，绝不使用
 *   "政治 / 性 / 赌博 / 颠覆"这类宽泛词，否则会拦掉平台自己的正常输出。
 *
 * 命中即拦。词表可随时增删；加词时务必自查：会不会误伤平台正常文案？
 */

const BLOCKED_TERMS: string[] = [
  // —— 淫秽色情（高精度词，避免单字"性"）——
  "淫秽", "色情", "黄片", "毛片", "约炮", "裸聊", "嫖娼", "卖淫", "强奸", "轮奸",
  "迷奸", "幼女", "成人影片", "成人视频", "色情网站", "情色",
  // —— 违禁违法 ——
  "制毒", "贩毒", "冰毒", "海洛因", "摇头丸", "枪支弹药", "炸弹制作", "自制炸弹",
  "恐怖袭击", "人肉炸弹", "买凶", "雇凶",
  // —— 政治高精度（避免宽泛的"政治""颠覆")——
  "颠覆国家", "分裂国家", "推翻政府", "打倒共产党", "法轮功", "六四事件", "8964",
  "台独", "港独", "藏独", "疆独", "反华", "辱华",
];

/** 归一化：去空白与常见分隔符/干扰符（对抗"色 情""色*情"这类初步变形），小写化 */
function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\s\u3000·.,，。、*_\-—~!！?？"'“”‘’()（）\[\]【】<>«»]/g, "");
}

/**
 * 扫描文本是否命中违禁词。命中返回命中的词，否则返回 null。
 * 注意：只用于用户输入与 AI 输出，**不要**用于平台自己的数据（会误伤）。
 */
export function findBlockedTerm(text: string | null | undefined): string | null {
  if (!text) return null;
  const n = normalize(text);
  if (!n) return null;
  for (const term of BLOCKED_TERMS) {
    if (n.includes(normalize(term))) return term;
  }
  return null;
}

