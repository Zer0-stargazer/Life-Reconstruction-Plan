function replaceField(content, nodeId, fieldName, newValue) {
  // 找到节点块
  const startPattern = `id: ${nodeId}, name:`;
  const startIdx = content.indexOf(startPattern);
  if (startIdx === -1) return content;
  
  // 找到字段
  const fieldPattern = `${fieldName}: '`;
  const fieldStartInBlock = content.indexOf(fieldPattern, startIdx);
  if (fieldStartInBlock === -1) return content;
  
  const valueStart = fieldStartInBlock + fieldPattern.length;
  
  // 找到字段值结束位置（处理转义单引号）
  let valueEnd = valueStart;
  while (true) {
    const nextQuote = content.indexOf("'", valueEnd);
    if (nextQuote === -1) break;
    // 检查是否是转义的
    if (content[nextQuote - 1] === '\\') {
      valueEnd = nextQuote + 1;
      continue;
    }
    valueEnd = nextQuote;
    break;
  }
  
  const oldValue = content.substring(valueStart, valueEnd);
  const escaped = newValue.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  
  return content.substring(0, valueStart) + escaped + content.substring(valueEnd);
}

