// FNV-1a hash
function hash2(name, field) {
  let h = 2166136261;
  const s = name + '|' + field;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

